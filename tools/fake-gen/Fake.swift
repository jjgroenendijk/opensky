// Writes one fake class: each property is stored, and each method records its arguments
// and answers from a value the test sets.

import SwiftSyntax

struct FakeWriter {
    let port: String
    let lineage: [ProtocolInfo]
    let defaults: Set<String>
    let ports: Set<String>
    let typeModules: [String: Set<String>]
    /// The modules the fakes' library may import.
    let visible: Set<String>
    let mainActorFakes: Set<String>

    var fakeName: String {
        "Fake\(port)"
    }

    /// Each file name and its text. A wide port's methods go in a second file, so no file
    /// passes the 600-line warning.
    func files() -> [(name: String, text: String)] {
        var context = TypeContext(associated: [:], ports: ports)
        context.mainActorFakes = mainActorFakes
        context.isNonisolated = !mainActorFakes.contains(fakeName)
        var lines: [String] = []
        var members: [DeclSyntax] = []
        var seen: Set<String> = []
        for info in lineage {
            for item in info.declaration.memberBlock.members {
                if let associated = item.decl.as(AssociatedTypeDeclSyntax.self) {
                    let constraint = associated.inheritanceClause?.inheritedTypes.first?.type
                    let fake = constraint.flatMap { context.fake(for: $0) } ?? "Never"
                    context.associated[associated.name.text] = fake
                    lines.append("    public typealias \(associated.name.text) = \(fake)")
                    continue
                }
                guard let key = memberKey(item.decl), !defaults.contains(key), seen.insert(key).inserted
                else { continue }
                members.append(item.decl)
            }
        }
        let functions = members.compactMap { $0.as(FunctionDeclSyntax.self) }
        let bases = functions.map(\.name.text)
        let overloaded = Set(bases.filter { name in bases.count(where: { $0 == name }) > 1 })
        let labelled = functions.map { labelKey($0) }
        let typed = Set(labelled.filter { key in labelled.count(where: { $0 == key }) > 1 })
        var parts: [Part] = []
        for member in members {
            if let variable = member.as(VariableDeclSyntax.self) {
                parts.append(property(variable, context: context))
            } else if let function = member.as(FunctionDeclSyntax.self) {
                parts.append(method(function, context: context, overloaded: overloaded, typed: typed))
            }
        }
        var modules: Set = ["OpenSkySessionInterface"]
        let names = members.flatMap { member in
            member.tokens(viewMode: .sourceAccurate).map(\.text)
        }
        for name in names {
            if let module = appleModule(name) {
                modules.insert(module)
            }
            guard name.first?.isUppercase == true else { continue }
            let reachable = visible.union(lineage.flatMap(\.imports))
            modules.formUnion(typeModules[name, default: []].intersection(reachable))
        }
        let imports = modules.sorted()
        let header = ["// Generated by tools/fake-gen from \(port); `make fakes` rewrites it.", ""]
            + imports.map { "public import \($0)" }
        var out = header
        out += ["", "/// Stores each property and records each call to `\(port)`."]
        // A Sendable port keeps the main actor, the only way mutable state is Sendable.
        let isolation = context.isNonisolated ? "nonisolated " : ""
        out += ["\(isolation)public final class \(fakeName): \(port) {"]
        out += lines
        out += parts.flatMap(\.stored)
        out += ["", "    public init() {}", "}"]
        let records = parts.map(\.record).filter { !$0.isEmpty }
        if !records.isEmpty {
            out += ["", "extension \(fakeName) {"]
            out += records.joined(separator: [""])
            out.append("}")
        }
        // The class body keeps only state, so a wide port stays under the type length limit.
        let behaviour = parts.map(\.members).filter { !$0.isEmpty }
        var methods: [String] = []
        if !behaviour.isEmpty {
            methods = ["", "\(isolation)extension \(fakeName) {"]
            methods += behaviour.joined(separator: [""])
            methods.append("}")
        }
        let splitLength = 500
        guard out.count + methods.count > splitLength else {
            return [("\(fakeName).swift", (out + methods + [""]).joined(separator: "\n"))]
        }
        return [
            ("\(fakeName).swift", (out + [""]).joined(separator: "\n")),
            ("\(fakeName)+Methods.swift", (header + methods + [""]).joined(separator: "\n"))
        ]
    }

    private func property(_ variable: VariableDeclSyntax, context: TypeContext) -> Part {
        guard let binding = variable.bindings.first,
              let name = binding.pattern.as(IdentifierPatternSyntax.self)?.identifier.text,
              let type = binding.typeAnnotation?.type
        else { return Part() }
        let stored = context.storable(type)
        if let value = context.emptyValue(for: type) {
            return Part(stored: ["    public var \(name): \(stored)" + (value == "nil" ? "" : " = \(value)")])
        }
        return Part(stored: ["    public var \(name)Value: \(stored)?"], members: [
            "    public var \(name): \(stored) {",
            "        get {",
            "            guard let \(name)Value else { preconditionFailure(\"\(fakeName).\(name) is unset\") }",
            "            return \(name)Value",
            "        }",
            "        set { \(name)Value = newValue }",
            "    }"
        ])
    }

    private func method(
        _ function: FunctionDeclSyntax, context outer: TypeContext, overloaded: Set<String>,
        typed: Set<String>
    ) -> Part {
        var context = outer
        let generics = function.genericParameterClause?.parameters.map(\.name.text) ?? []
        context.generics = Set(generics)
        let name = function.name.text
        let parameters = Array(function.signature.parameterClause.parameters)
        var key = name
        if overloaded.contains(name) {
            key = labelKey(function)
        }
        if typed.contains(key) {
            key += parameters.map { identifier($0.type.trimmedDescription) }.joined()
        }
        let recorded = parameters.filter { !isFunctionType($0.type) && !context.mentionsGeneric($0.type) }
        var out: [String] = []
        var record: [String] = []
        let recordName = identifier(key) + "Call"
        if recorded.isEmpty {
            out.append("    public var \(key)CallCount = 0")
        } else if recorded.count == 1, let only = recorded.first {
            out.append("    public var \(key)Calls: [\(context.storable(only.type))] = []")
        } else if recorded.count == 2 {
            let fields = recorded.map { "\(localName($0)): \(context.storable($0.type))" }
            out.append("    public var \(key)Calls: [(\(fields.joined(separator: ", ")))] = []")
        } else {
            // SwiftLint allows a tuple of two members at most, so a wider call gets a record.
            record = ["    nonisolated public struct \(recordName) {"]
            record += recorded.map { "        public let \(localName($0)): \(context.storable($0.type))" }
            record.append("    }")
            out.append("    public var \(key)Calls: [\(recordName)] = []")
        }
        let effects = function.signature.effectSpecifiers
        let throwsClause = effects?.throwsClause
        if let throwsClause {
            let errorType = throwsClause.type.map(\.trimmedDescription) ?? "any Error"
            out.append("    public var \(key)Error: (\(errorType))?")
        }
        let returnType = function.signature.returnClause?.type
        var answer: [String] = []
        if let returnType, returnType.trimmedDescription != "Void" {
            let stored = context.storable(returnType)
            if context.mentionsGeneric(returnType) {
                out.append("    public var \(key)Result: Any?")
                answer = [
                    "        guard let result = \(key)Result as? \(stored) else {",
                    "            preconditionFailure(\"\(fakeName).\(name) has no result\")",
                    "        }",
                    "        return result"
                ]
            } else if let value = context.emptyValue(for: returnType) {
                out.append("    public var \(key)Result: \(stored)" + (value == "nil" ? "" : " = \(value)"))
                answer = ["        return \(key)Result"]
            } else {
                out.append("    public var \(key)Result: \(stored)?")
                answer = [
                    "        guard let \(key)Result else {",
                    "            preconditionFailure(\"\(fakeName).\(name) has no result\")",
                    "        }",
                    "        return \(key)Result"
                ]
            }
        }
        let keepsResult = function.attributes.contains {
            $0.as(AttributeSyntax.self)?.attributeName.trimmedDescription == "discardableResult"
        }
        let stored = out
        out = []
        if keepsResult {
            out.append("    @discardableResult")
        }
        var signature = function.with(\.leadingTrivia, []).with(\.body, nil)
        signature.attributes = []
        signature.modifiers = [DeclModifierSyntax(name: .keyword(.public, trailingTrivia: .space))]
        let header = signature.trimmedDescription
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { "    " + $0.trimmingPrefixSpaces() }
        out += header.dropLast()
        out.append((header.last ?? "") + " {")
        if recorded.isEmpty {
            out.append("        \(key)CallCount += 1")
        } else if recorded.count == 1, let only = recorded.first {
            out.append("        \(key)Calls.append(\(localName(only)))")
        } else {
            let values = recorded.map { "\(localName($0)): \(localName($0))" }
            let open = recorded.count == 2 ? "(" : recordName + "("
            out.append("        \(key)Calls.append(\(open)\(values.joined(separator: ", "))))")
        }
        if throwsClause != nil {
            out.append("        if let \(key)Error {")
            out.append("            throw \(key)Error")
            out.append("        }")
        }
        out += answer
        out.append("    }")
        return Part(stored: stored, members: out, record: record)
    }

    /// `routeEvent` for `route(_ event:)`: the name and each label.
    private func labelKey(_ function: FunctionDeclSyntax) -> String {
        function.name.text + function.signature.parameterClause.parameters.map { parameter in
            let label = parameter.firstName.text == "_"
                ? (parameter.secondName?.text ?? "") : parameter.firstName.text
            return identifier(label)
        }.joined()
    }

    private func identifier(_ text: String) -> String {
        let letters = text.filter { $0.isLetter || $0.isNumber }
        return letters.prefix(1).uppercased() + letters.dropFirst()
    }

    private func localName(_ parameter: FunctionParameterSyntax) -> String {
        (parameter.secondName ?? parameter.firstName).text
    }
}

/// One protocol member: its state in the class, its behaviour in an extension, and the
/// record type of its calls when it has one.
struct Part {
    var stored: [String] = []
    var members: [String] = []
    var record: [String] = []
}

extension Substring {
    func trimmingPrefixSpaces() -> String {
        String(drop(while: { $0 == " " }))
    }
}
